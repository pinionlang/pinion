// Package codegen translates Pinion ASTs into Go source that runs on the
// dynamic runtime in runtime/pinionrt.
//
// The generated program is a single Go file (package main). Every Pinion
// value is an rt.Value; expressions are lowered to Go statements with
// temporaries so that evaluation is strictly left to right and control flow
// (return, break, continue, `?`, let-else) maps onto Go control flow.
package codegen

import (
	"fmt"
	"sort"
	"strconv"
	"strings"

	"github.com/pinionlang/pinion/internal/ast"
	"github.com/pinionlang/pinion/internal/token"
)

// Options configure generation.
type Options struct {
	RuntimeImport string              // import path of pinionrt in the generated module
	EntryModule   string              // module whose main is the entry point ("" single file)
	PathMap       func(string) string // maps ast file paths to paths shown in //line (nil = identity)
}

type module struct {
	path    string
	file    *ast.File
	prefix  string
	fns     map[string]*ast.FnDecl
	types   map[string]*ast.TypeDecl
	enums   map[string]*ast.EnumDecl
	ifaces  map[string]*ast.InterfaceDecl
	aliases map[string]*ast.AliasDecl
	lets    map[string]*ast.LetDecl
	imports map[string]string // local name -> module path
}

type program struct {
	opts     Options
	mods     map[string]*module
	order    []*module
	out      strings.Builder
	inits    strings.Builder
	names    map[string]string // go func name -> pinion name
	lineCols map[string]int    // "file:line" -> leftmost statement column
	tests    []string
}

var stdModules = map[string]bool{"fs": true, "env": true, "io": true, "time": true, "rand": true, "json": true, "http": true}

func mangle(path string) string {
	if path == "" {
		return ""
	}
	var b strings.Builder
	for _, r := range path {
		if r == '/' || r == '-' || r == '.' {
			b.WriteByte('_')
		} else {
			b.WriteRune(r)
		}
	}
	return b.String() + "__"
}

// Generate produces the Go source of the whole program.
func Generate(files []*ast.File, opts Options) ([]byte, error) {
	if opts.RuntimeImport == "" {
		opts.RuntimeImport = "pinionprog/pinionrt"
	}
	p := &program{opts: opts, mods: map[string]*module{}, names: map[string]string{}, lineCols: map[string]int{}}
	for _, f := range files {
		m := &module{path: f.Module, file: f, prefix: mangle(f.Module),
			fns: map[string]*ast.FnDecl{}, types: map[string]*ast.TypeDecl{}, enums: map[string]*ast.EnumDecl{},
			ifaces: map[string]*ast.InterfaceDecl{}, aliases: map[string]*ast.AliasDecl{}, lets: map[string]*ast.LetDecl{},
			imports: map[string]string{}}
		if _, dup := p.mods[m.path]; dup {
			return nil, fmt.Errorf("duplicate module %q", m.path)
		}
		p.mods[m.path] = m
		p.order = append(p.order, m)
		for _, imp := range f.Imports {
			m.imports[imp.Name()] = imp.Path
		}
		for _, d := range f.Decls {
			switch d := d.(type) {
			case *ast.FnDecl:
				m.fns[d.Name] = d
			case *ast.TypeDecl:
				m.types[d.Name] = d
			case *ast.EnumDecl:
				m.enums[d.Name] = d
			case *ast.InterfaceDecl:
				m.ifaces[d.Name] = d
			case *ast.AliasDecl:
				m.aliases[d.Name] = d
			case *ast.LetDecl:
				m.lets[d.Name] = d
			}
		}
	}
	for _, m := range p.order {
		for _, imp := range m.file.Imports {
			if strings.HasPrefix(imp.Path, "std/") {
				if !stdModules[strings.TrimPrefix(imp.Path, "std/")] {
					return nil, fmt.Errorf("%s: unknown std module %s", imp.Pos, imp.Path)
				}
				continue
			}
			if p.mods[imp.Path] == nil {
				return nil, fmt.Errorf("%s: unknown module %s", imp.Pos, imp.Path)
			}
		}
	}
	var gerr error
	func() {
		defer func() {
			if r := recover(); r != nil {
				if e, ok := r.(genError); ok {
					gerr = e
					return
				}
				panic(r)
			}
		}()
		p.genAll()
	}()
	if gerr != nil {
		return nil, gerr
	}
	var b strings.Builder
	b.WriteString("// Code generated by pinion. DO NOT EDIT.\n\npackage main\n\n")
	fmt.Fprintf(&b, "import rt %q\n\n", opts.RuntimeImport)
	b.WriteString("var _ = rt.UnitV\n\n")
	b.WriteString(p.out.String())
	b.WriteString("//line generated.go:1\nfunc init() {\n")
	b.WriteString(p.inits.String())
	keys := make([]string, 0, len(p.names))
	for k := range p.names {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	for _, k := range keys {
		fmt.Fprintf(&b, "\trt.FuncNames[%q] = %q\n", k, p.names[k])
	}
	keys = keys[:0]
	for k := range p.lineCols {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	for _, k := range keys {
		fmt.Fprintf(&b, "\trt.LineCols[%q] = %d\n", k, p.lineCols[k])
	}
	b.WriteString("}\n\n")
	b.WriteString("func main() {\n")
	mainFn := "nil"
	if em := p.entry(); em != nil {
		mainFn = "func() rt.Value { return " + em.fnName("main") + "() }"
	}
	fmt.Fprintf(&b, "\trt.Main(%s, []rt.Test{\n", mainFn)
	for _, t := range p.tests {
		b.WriteString("\t\t" + t + ",\n")
	}
	b.WriteString("\t})\n}\n")
	return []byte(b.String()), nil
}

func (p *program) entry() *module {
	if m := p.mods[p.opts.EntryModule]; m != nil && m.fns["main"] != nil {
		return m
	}
	for _, m := range p.order {
		if m.fns["main"] != nil {
			return m
		}
	}
	return nil
}

type genError struct{ msg string }

func (e genError) Error() string { return e.msg }

func fail(pos token.Pos, format string, args ...any) {
	panic(genError{fmt.Sprintf("%s: codegen: %s", pos, fmt.Sprintf(format, args...))})
}

// ---------- Go names ----------

func (m *module) fnName(n string) string        { return "f_" + m.prefix + n }
func (m *module) typeVar(n string) string       { return "T_" + m.prefix + n }
func (m *module) enumVar(n string) string       { return "E_" + m.prefix + n }
func (m *module) variantVar(e, v string) string { return "V_" + m.prefix + e + "_" + v }
func (m *module) globalVar(n string) string     { return "G_" + m.prefix + n }
func (m *module) methodName(t, n string) string { return "m_" + m.prefix + t + "_" + n }
func (m *module) initName(t string) string      { return "i_" + m.prefix + t }

func (p *program) qualName(m *module, n string) string {
	if m.path == "" {
		return n
	}
	return m.path + "." + n
}

// ---------- top level ----------

func (p *program) genAll() {
	for _, m := range p.order {
		for _, d := range m.file.Decls {
			switch d := d.(type) {
			case *ast.TypeDecl:
				fmt.Fprintf(&p.out, "var %s = &rt.TypeInfo{Name: %q, Module: %q, Class: %v}\n", m.typeVar(d.Name), d.Name, m.path, d.Kind == ast.KindClass)
			case *ast.EnumDecl:
				fmt.Fprintf(&p.out, "var %s = rt.NewEnum(%q, %q)\n", m.enumVar(d.Name), d.Name, m.path)
				for _, v := range d.Variants {
					fmt.Fprintf(&p.out, "var %s *rt.VariantInfo\n", m.variantVar(d.Name, v.Name))
				}
			case *ast.LetDecl:
				fmt.Fprintf(&p.out, "var %s = &rt.Global{}\n", m.globalVar(d.Name))
			}
		}
	}
	p.out.WriteString("\n")
	for _, m := range p.order {
		// enums first so that variant vars exist before type descriptors use them
		for _, d := range m.file.Decls {
			if d, ok := d.(*ast.EnumDecl); ok {
				p.genEnum(m, d)
			}
		}
	}
	for _, m := range p.order {
		for _, d := range m.file.Decls {
			switch d := d.(type) {
			case *ast.FnDecl:
				p.genFn(m, nil, d)
			case *ast.TypeDecl:
				p.genType(m, d)
			case *ast.LetDecl:
				g := p.newFn(m, nil)
				g.indent = 2
				val := g.expr(d.Value)
				fmt.Fprintf(&p.inits, "\t%s.Init = func() rt.Value {\n%s\t\treturn %s\n\t}\n", m.globalVar(d.Name), g.buf.String(), val)
			case *ast.TestDecl:
				p.genTest(m, d)
			}
		}
	}
}

func (p *program) genEnum(m *module, d *ast.EnumDecl) {
	tps := typeParamIdx(d.TypeParams)
	for _, v := range d.Variants {
		var names, types []string
		for _, f := range v.Fields {
			names = append(names, strconv.Quote(f.Name))
			types = append(types, p.typeDesc(m, nil, tps, f.Type))
		}
		fmt.Fprintf(&p.inits, "\t%s = %s.AddVariant(%q, %s, %s)\n", m.variantVar(d.Name, v.Name), m.enumVar(d.Name), v.Name,
			strSlice(names), "[]*rt.Type{"+strings.Join(types, ", ")+"}")
	}
}

func strSlice(quoted []string) string {
	if len(quoted) == 0 {
		return "nil"
	}
	return "[]string{" + strings.Join(quoted, ", ") + "}"
}

func typeParamIdx(tps []*ast.TypeParam) map[string]int {
	m := map[string]int{}
	for i, t := range tps {
		m[t.Name] = i
	}
	return m
}

func (p *program) genType(m *module, d *ast.TypeDecl) {
	tv := m.typeVar(d.Name)
	tps := typeParamIdx(d.TypeParams)
	var fields []string
	for _, f := range d.Fields {
		def := "nil"
		if f.Default != nil {
			g := p.newFn(m, d)
			g.indent = 2
			val := g.expr(f.Default)
			def = fmt.Sprintf("func() rt.Value {\n%s\t\treturn %s\n\t}", g.buf.String(), val)
		}
		fields = append(fields, fmt.Sprintf("{Name: %q, Type: %s, Pub: %v, Mut: %v, Default: %s}", f.Name,
			p.typeDesc(m, d, tps, f.Type), f.Pub, f.Mut, def))
	}
	fmt.Fprintf(&p.inits, "\t%s.Fields = []rt.FieldInfo{\n", tv)
	for _, f := range fields {
		fmt.Fprintf(&p.inits, "\t\t%s,\n", f)
	}
	p.inits.WriteString("\t}\n")
	for _, md := range d.Methods {
		if md.Body == nil {
			continue
		}
		p.genFn(m, d, md)
		var ps, args []string
		for i, pr := range md.Params {
			ps = append(ps, strconv.Quote(pr.Name))
			args = append(args, fmt.Sprintf("a[%d]", i))
		}
		fmt.Fprintf(&p.inits, "\t%s.AddMethod(%q, %s, func(self rt.Value, a []rt.Value) rt.Value { return %s(%s) })\n",
			tv, md.Name, strSlice(ps), m.methodName(d.Name, md.Name), strings.Join(append([]string{"self"}, args...), ", "))
	}
	if d.Init != nil && d.Init.Body != nil {
		p.genFn(m, d, d.Init)
		var ps, args []string
		for i, pr := range d.Init.Params {
			ps = append(ps, strconv.Quote(pr.Name))
			args = append(args, fmt.Sprintf("a[%d]", i))
		}
		if ps == nil {
			fmt.Fprintf(&p.inits, "\t%s.InitParams = []string{}\n", tv)
		} else {
			fmt.Fprintf(&p.inits, "\t%s.InitParams = %s\n", tv, strSlice(ps))
		}
		fmt.Fprintf(&p.inits, "\t%s.Init = func(a []rt.Value) rt.Value { return %s(%s) }\n", tv, m.initName(d.Name), strings.Join(args, ", "))
	}
}

func (p *program) genFn(m *module, owner *ast.TypeDecl, d *ast.FnDecl) {
	if d.Body == nil {
		return
	}
	g := p.newFn(m, owner)
	var goName, piName string
	var params []string
	switch {
	case d.IsInit:
		goName, piName = m.initName(owner.Name), p.qualName(m, owner.Name+".init")
		g.inInit = true
	case owner != nil:
		goName, piName = m.methodName(owner.Name, d.Name), p.qualName(m, owner.Name+"."+d.Name)
		params = append(params, "self rt.Value")
		g.scope.vars["self"] = &binding{goName: "self"}
	default:
		goName, piName = m.fnName(d.Name), p.qualName(m, d.Name)
	}
	p.names[goName] = piName
	var snapNames, snapArgs []string
	for _, pr := range d.Params {
		gn := g.declare(pr.Name, false)
		params = append(params, gn+" rt.Value")
		snapNames = append(snapNames, strconv.Quote(pr.Name))
		snapArgs = append(snapArgs, gn)
	}
	g.indent = 1
	// value snapshots (DESIGN 5.2): only installed when enabled at run time
	hasSelf, selfV := "false", "nil"
	if owner != nil && !d.IsInit {
		hasSelf, selfV = "true", "self"
	}
	snapNamesV := "nil"
	if len(snapNames) > 0 {
		snapNamesV = "[]string{" + strings.Join(snapNames, ", ") + "}"
	}
	g.buf.WriteString("\tif rt.SnapOn {\n\t\tdefer rt.SnapExit(" + strings.Join(append([]string{hasSelf, selfV, snapNamesV}, snapArgs...), ", ") + ")\n\t}\n")
	g.pos = d.Body.Pos
	val := g.blockValue(d.Body)
	g.emit("return %s", val)
	fmt.Fprintf(&p.out, "func %s(%s) rt.Value {\n%s}\n\n", goName, strings.Join(params, ", "), g.buf.String())
}

func (p *program) genTest(m *module, d *ast.TestDecl) {
	idx := len(p.tests)
	goName := fmt.Sprintf("t_%s%d", m.prefix, idx)
	p.names[goName] = "test " + strconv.Quote(d.Name)
	g := p.newFn(m, nil)
	g.indent = 1
	g.pos = d.Body.Pos
	if v := g.blockValue(d.Body); !isConst(v) {
		g.emit("_ = %s", v) // the last expression statement still runs
	}
	g.emit("return rt.UnitV")
	fmt.Fprintf(&p.out, "func %s() rt.Value {\n%s}\n\n", goName, g.buf.String())
	var effs []string
	for _, e := range d.Effects {
		effs = append(effs, strconv.Quote(e.Name))
	}
	p.tests = append(p.tests, fmt.Sprintf("{Name: %q, Effects: %s, Fn: %s}", d.Name, strSlice(effs), goName))
}

// ---------- type descriptors ----------

var builtinKinds = map[string]string{
	"Int": "rt.TInt", "Float": "rt.TFloat", "Bool": "rt.TBool", "Str": "rt.TStr", "Dec": "rt.TDec",
	"Bytes": "rt.TBytes", "Instant": "rt.TInstant", "Duration": "rt.TDuration", "Range": "rt.TRange",
	"Never": "rt.TAnyT",
}

var compositeKinds = map[string]string{
	"List": "rt.KList", "MutList": "rt.KMutList", "Map": "rt.KMap", "MutMap": "rt.KMutMap",
	"Set": "rt.KSet", "MutSet": "rt.KMutSet", "Result": "rt.KResult",
}

func (p *program) typeDesc(m *module, owner *ast.TypeDecl, tps map[string]int, t ast.TypeExpr) string {
	return p.typeDescD(m, owner, tps, t, 0)
}

func (p *program) typeDescD(m *module, owner *ast.TypeDecl, tps map[string]int, t ast.TypeExpr, depth int) string {
	if depth > 20 {
		return "rt.TAnyT"
	}
	switch t := t.(type) {
	case nil:
		return "rt.TUnit"
	case *ast.OptionalType:
		return "rt.TK(rt.KOpt, " + p.typeDescD(m, owner, tps, t.Elem, depth+1) + ")"
	case *ast.FnType:
		return "rt.TFn"
	case *ast.TupleType:
		if len(t.Elems) == 0 {
			return "rt.TUnit"
		}
		var es []string
		for _, e := range t.Elems {
			es = append(es, p.typeDescD(m, owner, tps, e, depth+1))
		}
		return "rt.TK(rt.KTuple, " + strings.Join(es, ", ") + ")"
	case *ast.NamedType:
		var args []string
		for _, a := range t.Args {
			args = append(args, p.typeDescD(m, owner, tps, a, depth+1))
		}
		argStr := ""
		if len(args) > 0 {
			argStr = ", " + strings.Join(args, ", ")
		}
		tm := m
		if t.Qualifier != "" {
			path, ok := m.imports[t.Qualifier]
			if !ok || p.mods[path] == nil {
				return "rt.TAnyT"
			}
			tm = p.mods[path]
		} else {
			if i, ok := tps[t.Name]; ok {
				return fmt.Sprintf("rt.TParam(%d)", i)
			}
			if t.Name == "Self" && owner != nil {
				return "rt.TObj(" + m.typeVar(owner.Name) + ")"
			}
			if k, ok := builtinKinds[t.Name]; ok {
				return k
			}
			if k, ok := compositeKinds[t.Name]; ok {
				return "rt.TK(" + k + argStr + ")"
			}
		}
		if tm.types[t.Name] != nil {
			return "rt.TObj(" + tm.typeVar(t.Name) + argStr + ")"
		}
		if tm.enums[t.Name] != nil {
			return "rt.TEnum(" + tm.enumVar(t.Name) + argStr + ")"
		}
		if a := tm.aliases[t.Name]; a != nil {
			return p.typeDescD(tm, nil, typeParamIdx(a.TypeParams), a.Type, depth+1)
		}
		if tm.ifaces[t.Name] != nil {
			return "rt.TAnyT"
		}
		if t.Qualifier == "" {
			switch t.Name {
			case "JsonError":
				return "rt.TObj(rt.JsonErrorType)"
			case "Utf8Error":
				return "rt.TObj(rt.Utf8ErrorType)"
			}
			if _, ok := builtinEnumNames[t.Name]; ok {
				return "rt.TEnum(rt.BuiltinEnums[" + strconv.Quote(t.Name) + "])"
			}
		}
		return "rt.TAnyT"
	}
	return "rt.TAnyT"
}

var builtinEnumNames = map[string]bool{"Round": true, "FsError": true, "JsonErrorKind": true, "ParseError": true}
